export function getStudioCopy(locale: StudioLocale) {
  return copy[locale];
}

export function getStageCopy(locale: StudioLocale, stageId: StudioStageId) {
  return stageCopy[locale][stageId];
}

export function getStageStatusCopy(
  locale: StudioLocale,
  status: StudioStageStatus,
) {
  return statusCopy[locale][status];
}

export function formatStudioDate(locale: StudioLocale, value: string) {
  return new Intl.DateTimeFormat(locale === "zh-CN" ? "zh-CN" : "en-US", {
    month: "short",
    day: "numeric",
    hour: "2-digit",
    minute: "2-digit",
  }).format(new Date(value));
}
